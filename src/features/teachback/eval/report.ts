import type { Rate, Summary } from "./metrics";
import type { PlantedResult } from "./plantedQuotes";

export type EvalSkill = {
  key: string;
  area: string;
  origin: string;
  node: { title: string; checkpoints: string[] };
};

export type FollowUpRun = {
  caseId: string;
  run: number;
  score: number;
  question: string;
  answer: string;
  passed: boolean;
  feedback: string;
};

type ReportInput = {
  summary: Summary;
  skills: EvalSkill[];
  planted: PlantedResult[];
  followUps: FollowUpRun[];
  /** Commit that last changed cases.json. It predates the run if the labels were frozen first. */
  labelsCommit: string;
  writtenAt: string;
  /** Hand-written reading of the results, from findings.md. */
  findings: string;
};

const percent = (rate: Rate) => `${(rate.rate * 100).toFixed(1)}%`;
const count = (rate: Rate) => `${rate.hits} of ${rate.total}`;
const range = (rate: Rate) => `${(rate.low * 100).toFixed(0)}-${(rate.high * 100).toFixed(0)}%`;
const usd = (value: number) => `$${value.toFixed(value < 0.01 ? 5 : 2)}`;
const inline = (text: string) => text.replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();

function table(headers: string[], rows: (string | number)[][]): string {
  const line = (cells: (string | number)[]) => `| ${cells.join(" | ")} |`;
  return [line(headers), line(headers.map(() => "---")), ...rows.map(line)].join("\n");
}

function disagreementEntry(result: Summary["results"][number]): string {
  const { evalCase, scores, wrongRuns, records } = result;
  const lines = [
    `### ${evalCase.id} (${evalCase.category})`,
    `Expected **${evalCase.expected}**, majority **${result.majority ?? "no verdict"}**, ${wrongRuns} of ${records.length} runs disagreed. Scores: ${scores.join(", ")}.`,
    "",
    `Why it was labelled that way: ${evalCase.why}`,
    "",
    `> ${inline(evalCase.text)}`,
  ];

  const worst = records.find((record) => record.verdict !== evalCase.expected) ?? records[0];
  if (worst) {
    const credited = worst.credited.map((item) => `"${inline(item.quote)}" for "${inline(item.checkpoint)}"`);
    lines.push("", `Run ${worst.run}: ${worst.met} of ${worst.total} met, score ${worst.score}.`);
    if (credited.length) lines.push(`- Credited: ${credited.join("; ")}`);
    if (worst.misconceptions.length) lines.push(`- Errors flagged: ${worst.misconceptions.map(inline).join(" ")}`);
    if (worst.rejected.length) lines.push(`- Quotes rejected: ${worst.rejected.map((quote) => `"${inline(quote)}"`).join("; ")}`);
  }
  return lines.join("\n");
}

export function renderReport({ summary: s, skills, planted, followUps, labelsCommit, writtenAt, findings }: ReportInput): string {
  const disagreements = s.results.filter((result) => result.wrongRuns > 0);
  const rejections = s.results.flatMap((result) =>
    result.records.flatMap((record) => record.rejected.map((quote) => ({ id: result.evalCase.id, run: record.run, quote }))),
  );
  const plantedRejected = planted.filter((item) => item.rejected).length;
  const hosts = Object.entries(s.callsByHost).map(([host, calls]) => `${host}: ${calls}`).join(", ");

  return `# Grading eval results

Generated by \`npm run eval\` from \`src/features/teachback/eval/results.json\`. Report written ${writtenAt}.

## Read this first

- **Who wrote the labels:** every label, and every explanation, was written by the AI that built this feature (Claude), not by a teacher or a domain expert. **They need a human spot check.** The disagreement list below is the place to start.
- **When:** the labels were committed in \`${labelsCommit}\` before the first grading run, so they were not adjusted to fit the results. The generated checkpoints came first, because the answers had to be written against them.
- **What this tests:** the written-explanation gate only (score of 70 or more). A real pass also needs a follow-up answer, so a false pass here is not yet a false proof. The follow-up gate was only spot-checked, on the false passes, in its own section below.
- **Sample size:** ${s.caseCount} cases is small. The ranges are 95% Wilson intervals on cases.

## Results

| Metric | Result | 95% range |
| --- | --- | --- |
| Agreement with the label (majority of 3 runs) | **${percent(s.agreement)}** (${count(s.agreement)} cases) | ${range(s.agreement)} |
| False-pass rate: should fail, but passed | **${percent(s.falsePass)}** (${count(s.falsePass)} cases) | ${range(s.falsePass)} |
| False-pass rate, counting every run | ${percent(s.falsePassRuns)} (${count(s.falsePassRuns)} runs) | not independent |
| Should fail, but passed on at least one run | ${percent(s.falsePassAnyRun)} (${count(s.falsePassAnyRun)} cases) | ${range(s.falsePassAnyRun)} |
| False-fail rate: should pass, but failed | **${percent(s.falseFail)}** (${count(s.falseFail)} cases) | ${range(s.falseFail)} |
| False-fail rate, counting every run | ${percent(s.falseFailRuns)} (${count(s.falseFailRuns)} runs) | not independent |
| Same verdict on all 3 runs | ${percent(s.consistency)} (${count(s.consistency)} cases) | ${range(s.consistency)} |
| Score spread between runs of one case | mean ${s.meanScoreRange.toFixed(1)} points, largest ${s.maxScoreRange} | |
| Quotes the model returned / rejected by code as not in the text | ${s.quotesReturned} / ${s.rejectedQuotes} | |
| Planted fake quotes rejected, no model involved | ${plantedRejected} of ${planted.length} | |
| Grading latency, p50 / p95 | ${(s.latencyP50Ms / 1000).toFixed(2)} s / ${(s.latencyP95Ms / 1000).toFixed(2)} s | |
| Runs that got no answer from any provider | ${s.erroredRuns} of ${s.runCount} | |
| Tokens, input / output | ${s.promptTokens.toLocaleString("en-CA")} / ${s.completionTokens.toLocaleString("en-CA")} | |
| Approximate cost | ${usd(s.costUsd)} in total, ${usd(s.costPerGradeUsd)} per grade | |

Cost uses the Cerebras list price for gpt-oss-120b ($0.35 input and $0.75 output per million tokens, read 2026-11-07) and token counts from each response. It is an estimate, not a bill. Latency was measured from the builder's laptop, around the whole \`gradeExplanation\` call including any retry. Model requests by host: ${hosts}.

## Findings

${findings.trim()}

## By kind of explanation

${table(
  ["Kind", "Cases", "Agreed", "False pass", "False fail", "Highest score in any run"],
  s.byCategory.map((row) => [row.name, row.cases, row.agreed, row.falsePasses, row.falseFails, row.highestScore]),
)}

## By skill

${table(
  ["Skill", "Area", "Checkpoints from", "Cases", "Agreed", "False pass", "False fail"],
  s.bySkill.map((row) => {
    const skill = skills.find((item) => item.key === row.name);
    return [skill?.node.title ?? row.name, skill?.area ?? "", skill?.origin ?? "", row.cases, row.agreed, row.falsePasses, row.falseFails];
  }),
)}

## Every disagreement

Each case where at least one run differed from its label: ${disagreements.length} of ${s.caseCount}.

${disagreements.map(disagreementEntry).join("\n\n") || "None."}

## Follow-up gate, spot check on the false passes

${followUps.length ? `${followUps.filter((item) => !item.passed).length} of ${followUps.length} follow-ups stopped the learner. This is a small separate check, not part of the numbers above. The answers were written for this check: each repeats the false belief or the pasted text, as a learner who doesn't understand might. Someone who looks up the right answer would get past this gate.

${table(
  ["Case", "Run", "Follow-up question", "Result"],
  followUps.map((item) => [item.caseId, item.run, inline(item.question), item.passed ? "**passed**" : "stopped"]),
)}` : "Not run."}

## Quotes rejected in the live runs

${rejections.length ? rejections.map((item) => `- ${item.id}, run ${item.run}: "${inline(item.quote)}"`).join("\n") : "None. The model did not return a quote that failed the check, so the planted test below is the evidence that the check works."}

## Planted fake quotes

These go through the real \`gradeExplanation\` with the model's reply replaced by a stub.

${table(["Planted quote", "Text", "Rejected"], planted.map((item) => [item.name, item.quote ? `"${inline(item.quote)}"` : "(empty)", item.rejected ? "yes" : "NO"]))}

## How it was run

- ${s.caseCount} labelled explanations across ${skills.length} skills, each graded 3 times through the public \`gradeExplanation\` from \`@/features/teachback\`, with no changes to the grader. ${s.runCount} grades in all.
- **Label rule:** pass means a fair reader finds at least 70% of the checkpoints plainly stated and no clearly false claim about the skill. Otherwise fail. This is stricter than the scoring formula, which forgives one false claim if every checkpoint is met.
- **Checkpoints:** ${skills.filter((skill) => skill.origin.startsWith("fixture")).length} skills use saved model output from the sample postings. ${skills.filter((skill) => skill.origin.startsWith("generated")).length} were generated live for this eval by the real map generator, from two short postings written for the eval.
- **To repeat it:** \`npm run eval -- --fresh\` (about ${s.modelCalls} model calls). The cases are in \`src/features/teachback/eval/cases.json\` and every raw run is in \`results.json\`.

The checkpoints tested:

${skills
  .map((skill) => `**${skill.node.title}** (${skill.origin})\n${skill.node.checkpoints.map((checkpoint, index) => `${index + 1}. ${checkpoint}`).join("\n")}`)
  .join("\n\n")}
`;
}
